import math
fs=48000.0; blocks=fs/32
out=["/* generated by tools/gen_vilnis.py */","#include <stdint.h>"]
sine=[int(round(32767*math.sin(2*math.pi*i/1024))) for i in range(1024)]
out.append("static const int16_t vl_sin[1024] = {"+",".join(map(str,sine))+"};")
# LPG decay: tau 15 ms .. 4 s, per-sample coefficient in Q20
k=[]
for i in range(128):
    tau=0.015*(4.0/0.015)**(i/127)
    k.append(max(1,int(round((1-math.exp(-1/(tau*fs)))*(1<<20)))))
out.append("static const uint16_t vl_dcy[128] = {"+",".join(map(str,k))+"};")
# pulser: 0 off, 1..127 = 0.25 Hz .. 32 Hz, phase increment per block
p=[0]
for i in range(1,128):
    hz=0.25*(32/0.25)**((i-1)/126)
    p.append(int(round(hz/blocks*2**32)))
out.append("static const uint32_t vl_puls[128] = {"+",".join(map(str,p))+"};")
hz=[0]+[int(round(100*0.25*(32/0.25)**((i-1)/126))) for i in range(1,128)]
out.append("static const uint16_t vl_puls_chz[128] = {"+",".join(map(str,hz))+"};   /* centi-Hz, for the text */")
import os
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables.h"),"w").write("\n".join(out)+"\n")
